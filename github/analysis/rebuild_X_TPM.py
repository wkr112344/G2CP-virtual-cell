"""Rebuild X_TPM.npy, the expression input of the DepMap positive control (S13-S15).

Why this script exists
----------------------
`X_TPM.npy` (908 cell lines x 19,177 protein-coding genes, float32) is the only numerical input of the
reproducible path that is not shipped with the archive: it is a straight projection of the public DepMap
21Q2 expression matrix onto the 908 analysed cell lines, so it can be regenerated byte-for-byte from the
public file instead of being redistributed. Everything else the positive control needs (Y_CERES,
Y_Chronos, common_observed_mask, split.json, depmap_index.json, cell_order.txt, the frozen predictions)
does ship under `zenodo/source_data/`.

Input
-----
DepMap Public 21Q2 `OmicsExpressionProteinCodingGenesTPMLogp1.csv` (public, depmap.org). The file is
already log2(TPM+1) and already restricted to protein-coding genes, and its column order defines the gene
axis of X_TPM; no gene filtering or reordering is applied.

Rule
----
1. Read the cell identifiers from `zenodo/source_data/depmap_analysis_ready_20260929/index/cell_order.txt`
   (908 lines, the row axis of Y_CERES/Y_Chronos).
2. Select exactly those rows from the expression file and reorder them to match cell_order.txt.
3. Keep every gene column in the file's own order, cast to float32.
4. Save as `X_TPM.npy` and print shape / gene count / sha256.

Usage
-----
    python github/analysis/rebuild_X_TPM.py /path/to/OmicsExpressionProteinCodingGenesTPMLogp1.csv [--out DIR]

Then either put the result in the directory named by `G2CP_ALIGNED_DIR`, or export
`G2CP_ALIGNED_DIR=<DIR>` before running `run_all.sh`, which will then execute the positive-control step.

Acceptance check
----------------
The rebuild is correct when `positive_control_expression_ridge.py` reproduces the archived S13 medians
(for example ridge_CERES evaluated on CERES: cell_raw_median 0.9345, cell_zres_median 0.1432) and the
audit step of `run_all.sh` reports no mismatch. Shape and cell order are checked here; the numerical
check is the one that actually certifies the matrix.
"""
import argparse
import hashlib
import os
import sys

import numpy as np
import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CELL_ORDER = os.path.join(ROOT, "zenodo", "source_data", "depmap_analysis_ready_20260929", "index", "cell_order.txt")
N_GENES_EXPECTED = 19177
N_CELLS_EXPECTED = 908


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("omics_csv", help="DepMap 21Q2 OmicsExpressionProteinCodingGenesTPMLogp1.csv")
    ap.add_argument("--out", default=None, help="output directory (default: current working directory)")
    a = ap.parse_args()

    cells = [l.strip() for l in open(CELL_ORDER) if l.strip()]
    assert len(cells) == N_CELLS_EXPECTED, "cell_order.txt has %d lines, expected %d" % (len(cells), N_CELLS_EXPECTED)
    print("[1/4] %d cell identifiers from cell_order.txt" % len(cells))

    # The first column holds the cell-line identifiers (ACH-xxxxxx); the rest are genes.
    df = pd.read_csv(a.omics_csv, index_col=0)
    print("[2/4] expression file: %d cells x %d columns" % (df.shape[0], df.shape[1]))

    missing = [c for c in cells if c not in df.index]
    if missing:
        sys.exit("ERROR: %d cell lines from cell_order.txt are absent from the expression file, e.g. %s"
                 % (len(missing), missing[:5]))

    X = df.loc[cells].to_numpy(dtype=np.float32)
    del df
    print("[3/4] selected %d x %d, float32" % X.shape)

    if X.shape[1] != N_GENES_EXPECTED:
        print("WARNING: %d gene columns, the analysed matrix had %d. Check that the input is the 21Q2 "
              "protein-coding expression file and not a later release." % (X.shape[1], N_GENES_EXPECTED))
    if not np.isfinite(X).all():
        sys.exit("ERROR: non-finite values in the selected matrix")

    out_dir = a.out or os.getcwd()
    os.makedirs(out_dir, exist_ok=True)
    path = os.path.join(out_dir, "X_TPM.npy")
    np.save(path, X)
    h = hashlib.sha256(open(path, "rb").read()).hexdigest()
    print("[4/4] wrote %s" % path)
    print("      shape %s  dtype %s  genes %d" % (X.shape, X.dtype, X.shape[1]))
    print("      sha256 %s" % h)
    print("      row 0 = %s, row %d = %s" % (cells[0], len(cells) - 1, cells[-1]))
    print("Next: export G2CP_ALIGNED_DIR=%s and run ./run_all.sh; the positive-control step then runs and "
          "must reproduce the S13-S15 values." % out_dir)


if __name__ == "__main__":
    main()
